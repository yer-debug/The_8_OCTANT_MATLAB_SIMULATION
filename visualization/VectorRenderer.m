classdef VectorRenderer
    %VECTORRENDERER Draw a point, its position vector, and decomposition.
    methods (Static)
        function handles = draw(ax, point, showComponents, config)
            handles = {};
            handles{end + 1} = quiver3(ax, 0, 0, 0, point(1), point(2), point(3), 0, ...
                'Color', config.vectorColor, 'LineWidth', 2.2, ...
                'MaxHeadSize', 0.35, 'HandleVisibility', 'off');
            handles{end + 1} = scatter3(ax, point(1), point(2), point(3), 82, ...
                config.pointColor, 'filled', 'MarkerEdgeColor', [1, 1, 1], ...
                'LineWidth', 0.8, 'HandleVisibility', 'off');
            handles{end + 1} = text(ax, point(1), point(2), point(3), ...
                sprintf('  P(%.2f, %.2f, %.2f)', point(1), point(2), point(3)), ...
                'Color', [0.97, 0.94, 0.87], 'FontSize', 9, ...
                'FontWeight', 'bold', 'HandleVisibility', 'off');

            if showComponents
                componentColor = config.componentColor;
                handles{end + 1} = plot3(ax, [0, point(1)], [0, 0], [0, 0], ...
                    '--', 'Color', componentColor, 'LineWidth', 1.3, ...
                    'HandleVisibility', 'off');
                handles{end + 1} = plot3(ax, [point(1), point(1)], ...
                    [0, point(2)], [0, 0], '--', 'Color', componentColor, ...
                    'LineWidth', 1.3, 'HandleVisibility', 'off');
                handles{end + 1} = plot3(ax, [point(1), point(1)], ...
                    [point(2), point(2)], [0, point(3)], '--', ...
                    'Color', componentColor, 'LineWidth', 1.3, ...
                    'HandleVisibility', 'off');
            end
        end
    end
end