classdef SatelliteRenderer
    %SATELLITERENDERER Draw satellite markers and illustrative trail curves.
    methods (Static)
        function handles = drawTrails(ax, trails, color, visible)
            handles = cell(1, size(trails, 3));
            for index = 1:size(trails, 3)
                path = trails(:, :, index);
                handles{index} = plot3(ax, path(:, 1), path(:, 2), path(:, 3), ...
                    ':', 'Color', color, 'LineWidth', 1.1, ...
                    'Visible', matlab.lang.OnOffSwitchState(visible), ...
                    'HandleVisibility', 'off');
            end
        end

        function [marker, label] = drawMarker(ax, position, satelliteId)
            marker = scatter3(ax, position(1), position(2), position(3), ...
                48, [0.69, 0.74, 0.75], 'filled', ...
                'MarkerEdgeColor', [0.12, 0.16, 0.17], ...
                'HandleVisibility', 'off');
            label = text(ax, position(1), position(2), position(3), ...
                ['  ', satelliteId], 'Color', [0.69, 0.74, 0.75], ...
                'FontSize', 8, 'FontWeight', 'bold', ...
                'HandleVisibility', 'off');
        end
    end
end